#!/usr/bin/env python3
"""Build the image resources that go inside the app.

Usage: python3 scripts/make_icon_res.py <src/res dir> <out dir>

Writes <out dir>/icons.r plus the binary files it reads:
  'PICT' 128.. "<name>.pict"    every src/res/*.pict (file minus 512-byte
                                header), found by name by load_pict_handle
  'TEXT' 128 "iconorder.txt"    icon names, one per line, in sprite order
  'PIcn' 128                    40 px page icons, trimmed to their ink

'PIcn' layout (big-endian), icons in iconorder.txt order:
  u16 count
  u32 offset[count + 1]          from the start of the resource
  per icon: u8 left, top, width, height, then height rows of
            (width + 7) / 8 bytes, 1 bit per pixel, 1 = black
"""
import os, struct, sys

SIZE = 40

def u16(b, i):
    return int.from_bytes(b[i:i+2], 'big')

def unpackbits(d, n):
    out = bytearray(); i = 0
    while len(out) < n:
        c = d[i]; i += 1
        if c < 128:
            out += d[i:i+c+1]; i += c + 1
        elif c > 128:
            out += bytes([d[i]]) * (257 - c); i += 1
    return bytes(out[:n])

def decode_pict(path):
    """40x40 PICT v2 holding one BitsRect / PackBitsRect -> rows of 0/1."""
    b = open(path, 'rb').read()[512:]
    for op in (b'\x00\x98', b'\x00\x90'):
        i = b.find(op, 10)
        if i >= 0 and i % 2 == 0:
            break
    else:
        sys.exit(f'{path}: no bitmap opcode')
    packed = op == b'\x00\x98'
    i += 2
    rb = u16(b, i); is_pixmap = rb & 0x8000; rb &= 0x3FFF
    top, left, bot, right = (u16(b, i + k) for k in (2, 4, 6, 8))
    w, h = right - left, bot - top
    if (w, h) != (SIZE, SIZE):
        sys.exit(f'{path}: {w}x{h}, expected {SIZE}x{SIZE}')
    if is_pixmap:
        depth = u16(b, i + 28)
        ct = i + 46
        n = u16(b, ct + 6) + 1
        black = set()
        for k in range(n):
            e = ct + 8 + k * 8
            lum = 0.30 * u16(b, e + 2) + 0.59 * u16(b, e + 4) + 0.11 * u16(b, e + 6)
            if lum < 32768:
                black.add(u16(b, e))
        p = ct + 8 + n * 8 + 18
    else:
        depth = 1
        p = i + 10 + 18
    rows = []
    for _ in range(h):
        if packed and rb >= 8:
            cnt = b[p] if rb <= 250 else u16(b, p)
            p += 1 if rb <= 250 else 2
            row = unpackbits(b[p:p+cnt], rb); p += cnt
        else:
            row = b[p:p+rb]; p += rb
        if depth == 8:
            rows.append([1 if row[x] in black else 0 for x in range(w)])
        elif depth == 1:
            rows.append([(row[x >> 3] >> (7 - (x & 7))) & 1 for x in range(w)])
        else:
            sys.exit(f'{path}: {depth}-bit pixels not supported')
    return rows

def trim(rows):
    ys = [y for y in range(SIZE) if any(rows[y])]
    if not ys:
        return bytes(4)
    xs = [x for x in range(SIZE) if any(rows[y][x] for y in ys)]
    top, left = ys[0], xs[0]
    h, w = ys[-1] - top + 1, xs[-1] - left + 1
    out = bytearray([left, top, w, h])
    for y in range(top, top + h):
        bits = rows[y][left:left+w] + [0] * 7
        out += bytes(sum(bits[x+k] << (7 - k) for k in range(8))
                     for x in range(0, w, 8))
    return bytes(out)

def main():
    src, out = sys.argv[1], sys.argv[2]
    os.makedirs(out, exist_ok=True)
    names = [l.strip() for l in open(os.path.join(src, 'iconorder.txt'))
             if l.strip()]
    icons = [trim(decode_pict(os.path.join(src, 'page_icons', n + '.pict')))
             for n in names]
    offs = [2 + 4 * (len(icons) + 1)]
    for ic in icons:
        offs.append(offs[-1] + len(ic))
    pack = struct.pack(f'>H{len(offs)}L', len(icons), *offs) + b''.join(icons)
    open(os.path.join(out, 'pageicons.bin'), 'wb').write(pack)

    absout = os.path.abspath(out)
    order = os.path.abspath(os.path.join(src, 'iconorder.txt'))
    picts = sorted(f for f in os.listdir(src) if f.endswith('.pict'))
    with open(os.path.join(out, 'icons.r'), 'w') as f:
        f.write('/* Generated by scripts/make_icon_res.py -- do not edit. */\n\n')
        for rid, name in enumerate(picts, 128):
            if len(name) > 255 or '"' in name:
                sys.exit(f'{name}: not usable as a resource name')
            body = open(os.path.join(src, name), 'rb').read()[512:]
            binname = name[:-5] + '.bin'
            open(os.path.join(out, binname), 'wb').write(body)
            f.write(f'data \'PICT\' ({rid}, "{name}") {{\n'
                    f'    $$read("{absout}/{binname}")\n}};\n\n')
        f.write(f'data \'TEXT\' (128, "iconorder.txt") {{\n'
                f'    $$read("{order}")\n}};\n\n'
                f'data \'PIcn\' (128) {{\n'
                f'    $$read("{absout}/pageicons.bin")\n}};\n')
    print(f'{len(icons)} page icons, {len(pack)} bytes; {len(picts)} pictures')

if __name__ == '__main__':
    main()
