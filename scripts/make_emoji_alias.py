#!/usr/bin/env python3
"""Generate src/core/helpers/emoji_alias.c from scripts/emoji_alias.txt.

Usage: python3 scripts/make_emoji_alias.py [emoji-test.txt]

With emoji-test.txt (unicode.org/Public/emoji/<ver>/emoji-test.txt) it also
reports every fully-qualified emoji that still finds no sprite.
"""
import os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SPRITE_C = os.path.join(ROOT, 'src/core/helpers/emoji_sprite.c')
ALIAS_TXT = os.path.join(ROOT, 'scripts/emoji_alias.txt')
OUT_C = os.path.join(ROOT, 'src/core/helpers/emoji_alias.c')

def load_table():
    src = open(SPRITE_C, encoding='utf-8').read()
    ents = re.findall(r'\{ "((?:\\x[0-9a-f]{2})+)",\s*-?\d+,\s*-?\d+, "[^"]*" \}', src)
    return [bytes(int(h, 16) for h in re.findall(r'\\x([0-9a-f]{2})', s)).decode()
            for s in ents]

def key16(cp):
    # The C side keys on the low 16 bits: BMP emoji are < 0x3000 and the
    # rest live in U+1F000..U+1FFFF, so the two never collide.
    assert cp < 0x3000 or 0x1F000 <= cp <= 0x1FFFF, hex(cp)
    return cp & 0xFFFF

def load_aliases(index):
    aliases = {}
    for n, line in enumerate(open(ALIAS_TXT, encoding='utf-8'), 1):
        line = line.split('#', 1)[0].split()
        if not line:
            continue
        src = int(line[0], 16)
        dst = ''.join(chr(int(c, 16)) for c in line[1:])
        if chr(src) in index:
            sys.exit(f'line {n}: U+{src:X} is already on the sprite sheet')
        if dst not in index:
            sys.exit(f'line {n}: target {line[1:]} is not on the sprite sheet')
        if key16(src) in aliases:
            sys.exit(f'line {n}: U+{src:X} listed twice')
        aliases[key16(src)] = (src, index[dst])
    return aliases

def find_trimmed(s, index):
    while True:
        if s in index:
            return index[s]
        z = s.rfind('‍')
        if z < 0:
            return None
        s = s[:z]

def fallback(s, index, table, aliases):
    """Mirror of emoji_find_fallback() in emoji_sprite.c."""
    if s in index:
        return index[s]
    s = ''.join(c for c in s if not 0x1F3FB <= ord(c) <= 0x1F3FF)
    hit = find_trimmed(s, index)
    if hit is not None:
        return hit
    if s[0] in index:
        return index[s[0]]
    cp = ord(s[0])
    if not (cp < 0x10000 or 0x1F000 <= cp <= 0x1FFFF) or key16(cp) not in aliases:
        return None
    t = aliases[key16(cp)][1]
    for head in (table[t][0], table[t]):
        hit = find_trimmed(head + s[1:], index)
        if hit is not None:
            return hit
    return t

def main():
    table = load_table()
    index = {s: i for i, s in enumerate(table)}
    aliases = load_aliases(index)
    keys = sorted(aliases)

    with open(OUT_C, 'w', encoding='utf-8') as f:
        f.write('/* Auto-generated by scripts/make_emoji_alias.py from\n'
                ' * scripts/emoji_alias.txt -- edit those, not this file.\n'
                ' *\n'
                ' * Look-alikes for emoji the sprite sheet does not have: the\n'
                ' * low 16 bits of the missing codepoint (sorted) and the\n'
                ' * EMOJI_TABLE index to show instead. */\n'
                '#include "emoji_sprite.h"\n\n')
        f.write(f'#define EMOJI_ALIAS_COUNT {len(keys)}\n\n')
        f.write('static const unsigned short kAliasFrom[EMOJI_ALIAS_COUNT] = {\n')
        for i in range(0, len(keys), 10):
            f.write('    ' + ', '.join(f'0x{k:04X}' for k in keys[i:i+10]) + ',\n')
        f.write('};\n\n')
        f.write('static const short kAliasTo[EMOJI_ALIAS_COUNT] = {\n')
        for i in range(0, len(keys), 10):
            f.write('    ' + ', '.join(f'{aliases[k][1]:4d}' for k in keys[i:i+10]) + ',\n')
        f.write('};\n\n')
        f.write('''const EmojiSprite *emoji_alias(unsigned long cp)
{
    if (cp >= 0x10000UL && (cp < 0x1F000UL || cp > 0x1FFFFUL)) return NULL;
    unsigned short key = (unsigned short)cp;
    int lo = 0, hi = EMOJI_ALIAS_COUNT - 1;
    while (lo <= hi) {
        int mid = (lo + hi) >> 1;
        if (kAliasFrom[mid] == key) return &EMOJI_TABLE[kAliasTo[mid]];
        if (kAliasFrom[mid] < key) lo = mid + 1;
        else                       hi = mid - 1;
    }
    return NULL;
}
''')
    print(f'{len(keys)} aliases -> {os.path.relpath(OUT_C, ROOT)}')

    if len(sys.argv) > 1:
        missing = []
        for line in open(sys.argv[1], encoding='utf-8'):
            if line.startswith('#') or 'fully-qualified' not in line:
                continue
            cps = [int(c, 16) for c in line.split(';')[0].split() if c != 'FE0F']
            s = ''.join(map(chr, cps))
            if fallback(s, index, table, aliases) is None:
                missing.append(line.split('#', 1)[1].strip())
        print(f'{len(missing)} emoji without a sprite')
        for m in missing:
            print('  ' + m)

if __name__ == '__main__':
    main()
